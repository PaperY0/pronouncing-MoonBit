#!/usr/bin/env node
// gen_cmudict.mjs — 由上游 CMUdict 0.7b 生成 MoonBit 嵌入数据模块。
//
// 数据源：data/upstream/cmudict-0.7b
//   (c) 1993-2015 Carnegie Mellon University — 见 data/README.md（BSD-like， unrestricted）
//   官方源：https://svn.code.sf.net/p/cmusphinx/code/trunk/cmudict/cmudict-0.7b
//
// 解析规则与 Python `pronouncing.parse_cmu` 对齐：
//   - 跳过以 ';' 开头的注释行与空行；
//   - 按第一个空白把行切成 headword 与 phones；
//   - headword 去掉 '(n)' 变体后缀并转小写（pronouncing: word.split('(',1)[0].lower()）；
//   - phones 规范化为单空格连接（去前导/尾随空白）。
//     刻意差异：上游 raw 文件用两个空格分隔 headword/phones，pronouncing 的
//     split(" ",1) 会留下前导空格；这里规范化为单空格，与 pronouncing doctest
//     的干净输出一致，且对所有算法语义等价（stresses 抽数字 / rhyming_part 与
//     search 均按空白分词）。详见 README「与上游的刻意差异」。
//
// 产出：/cmudict_data.mbt
//   - N 个 const 多行字符串（MoonBit `#|` 行前缀语法，内容零转义），每块 CHUNK_LINES 行；
//   - 一个 cmudict_lines() 解析函数（按行 split，保序）。
//   每行格式："headword phones"（headword 已小写去变体后缀，phones 单空格）。

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.dirname(HERE);
const SRC = path.join(ROOT, "data", "upstream", "cmudict-0.7b");
const OUT = path.join(ROOT, "cmudict_data.mbt");
const CHUNK_LINES = 4000;

function parse(src) {
  const lines = fs.readFileSync(src, "utf8").split(/\r?\n/);
  const entries = [];
  let skippedComments = 0;
  for (const raw of lines) {
    const line = raw.trim();
    if (line.length === 0) continue;
    if (line.startsWith(";")) { skippedComments++; continue; }
    const m = line.match(/^(\S+)\s+(.*)$/);
    if (!m) continue;
    let word = m[1].split("(", 1)[0].toLowerCase();
    const phones = m[2].trim().split(/\s+/).join(" ");
    if (phones.length === 0) continue;
    // headword 内不应含换行（#| 原始字符串按行切）
    if (/[\n\r]/.test(word)) throw new Error("word contains newline: " + word);
    entries.push(word + " " + phones);
  }
  return { entries, skippedComments };
}

function main() {
  const { entries, skippedComments } = parse(SRC);
  const nchunks = Math.ceil(entries.length / CHUNK_LINES);
  const parts = [
    "// Code generated by tools/gen_cmudict.mjs — DO NOT EDIT.",
    "// Source: data/upstream/cmudict-0.7b (CMUdict 0.7b)",
    "// (c) 1993-2015 Carnegie Mellon University — see data/README.md",
    "// Official: https://svn.code.sf.net/p/cmusphinx/code/trunk/cmudict/cmudict-0.7b",
    "//",
    "// Each line: \"headword phones\" — headword lowercased with '(n)' variant suffix",
    "// stripped; phones single-space joined. Order preserved from upstream so that",
    "// search()/search_stresses() iterate pronunciations in dictionary order exactly",
    "// like Python pronouncing. Parse rules mirror pronouncing.parse_cmu.",
    "//",
    `// Generated: ${entries.length} entries, ${skippedComments} comment lines skipped, CHUNK_LINES=${CHUNK_LINES}.`,
    "",
  ];
  for (let c = 0; c < nchunks; c++) {
    const chunk = entries.slice(c * CHUNK_LINES, (c + 1) * CHUNK_LINES);
    parts.push("///|");
    parts.push(`const CMUDICT_${String(c).padStart(2, "0")} : String = #|`);
    for (const e of chunk) parts.push("#|" + e);
    parts.push("");
  }
  parts.push("///|");
  parts.push("/// 全部 CMUdict 条目（保序）。每行 \"headword phones\"。");
  parts.push("/// 数据本体由 tools/gen_cmudict.mjs 从 data/upstream/cmudict-0.7b 生成。");
  parts.push("pub fn cmudict_lines() -> Array[String] {");
  parts.push("  let out : Array[String] = []");
  for (let c = 0; c < nchunks; c++) {
    parts.push(`  extend_with_split(out, CMUDICT_${String(c).padStart(2, "0")})`);
  }
  parts.push("  out");
  parts.push("}");
  parts.push("");
  parts.push("///|");
  parts.push("/// 把一个 const 块按行切成 String 追加到 out。");
  parts.push("fn extend_with_split(out : Array[String], chunk : String) -> Unit {");
  parts.push('  for line in chunk.split("\\n") {');
  parts.push("    let s = line.to_owned()");
  parts.push("    if s.length() > 0 {");
  parts.push("      out.push(s)");
  parts.push("    }");
  parts.push("  }");
  parts.push("}");
  parts.push("");
  fs.writeFileSync(OUT, parts.join("\n") + "\n", "utf8");
  const kb = fs.statSync(OUT).size / 1024;
  console.log(`[wrote] ${OUT} (${kb.toFixed(1)} KB, ${entries.length} entries, ${nchunks} chunks)`);
}

main();